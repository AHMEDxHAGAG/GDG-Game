/**
 * Build-time availability of optimized character artwork.
 * Run assets:prepare after updating originals; dev/build/test refresh availability.
 */
import { mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const charactersDir = join(root, 'public', 'assets', 'characters');
const outFile = join(root, 'src', 'generated', 'artwork-manifest.ts');

const EXTENSIONS = /\.webp$/i;

/** Track ids that have a real illustration available. */
const available = new Set();
try {
  for (const entry of readdirSync(charactersDir)) {
    // Responsive size variants are not separate characters.
    if (EXTENSIONS.test(entry) && !/-\d+\./.test(entry)) available.add(entry.replace(EXTENSIONS, ''));
  }
} catch {
  // No characters directory yet — every track falls back to the placeholder.
}

const entries = [...available].sort();
const list = entries.map((id) => `  '${id}',`).join('\n');

const contents = `// AUTO-GENERATED by tools/generate-artwork-manifest.mjs — do not edit.
// Run \`npm run build\` / \`npm run dev\` / \`npm run test\` to regenerate.

/** Track ids with real character artwork in \`public/assets/characters/\`. */
export const ARTWORK_IDS = [
${list}
] as const;

export type ArtworkId = (typeof ARTWORK_IDS)[number];

const available = new Set<string>(ARTWORK_IDS);

/** True when a real illustration exists for this track. */
export function hasArtwork(trackId: string): boolean {
  return available.has(trackId);
}
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, contents, 'utf8');

console.log(
  entries.length > 0
    ? `[artwork] ${entries.length} character artwork file(s) found: ${entries.join(', ')}`
    : '[artwork] no character artwork found — all tracks use the designed placeholder',
);
