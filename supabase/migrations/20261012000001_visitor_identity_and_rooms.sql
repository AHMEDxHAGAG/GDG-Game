create or replace function public.enforce_room_cap_four()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  existing integer;
begin
  select count(*) into existing
  from public.room_members
  where room_id = new.room_id;

  if existing >= 4 then
    raise exception 'room_full' using errcode = 'P0001';
  end if;

  return new;
end;
$$;

drop trigger if exists room_members_cap_four on public.room_members;
create trigger room_members_cap_four
  before insert on public.room_members
  for each row execute function public.enforce_room_cap_four();

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists visitors_touch_updated_at on public.visitors;
create trigger visitors_touch_updated_at
  before update on public.visitors
  for each row execute function public.touch_updated_at();

-- Six hex characters from an unambiguous alphabet — `0-9A-F` has no I/O/1/0
-- lookalikes to mistype when reading a code off a projector. Sixteen million
-- values, and the unique constraint plus the retry in `create_room` make a
-- collision a non-event.
create or replace function public.generate_join_code()
returns text
language sql
volatile
set search_path = public
as $$
  select upper(substring(encode(extensions.gen_random_bytes(8), 'hex') from 1 for 6));
$$;

-- ------------------------------------------------------------------ --
-- Functions
--
-- All SECURITY DEFINER, because `anon` holds no table privileges and every
-- rule has to be checked in one place. None of them can widen a caller's
-- rights beyond what their own arguments already prove: the id they present
-- is the only identity in play.
-- ------------------------------------------------------------------ --

/** Creates or renames the visitor. Safe to call on every keystroke's settle. */
create or replace function public.claim_visitor(p_visitor_id uuid, p_name text)
returns public.visitors
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_name text := left(btrim(coalesce(p_name, '')), 24);
  v_row public.visitors;
begin
  if p_visitor_id is null then
    raise exception 'unknown_visitor' using errcode = 'P0001';
  end if;

  if char_length(v_name) = 0 then
    raise exception 'invalid_name' using errcode = 'P0001';
  end if;

  insert into public.visitors (id, display_name)
  values (p_visitor_id, v_name)
  on conflict (id) do update
    set display_name = excluded.display_name
  returning * into v_row;

  return v_row;
end;
$$;

/**
 * The room and its roster, in one payload.
 *
 * Reads across `rooms`, `room_members` and `visitors` at once, which is why it
 * is a function rather than a query the client could make: without this,
 * granting `anon` any table access to let PostgREST join them would expose
 * every membership in the database.
 *
 * Names come back, so the client needs no table privileges of its own.
 */
create or replace function public.get_room(p_code text)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_room public.rooms;
  v_members jsonb;
begin
  select * into v_room
  from public.rooms
  where join_code = upper(btrim(coalesce(p_code, '')));

  if not found then
    raise exception 'room_not_found' using errcode = 'P0001';
  end if;

  select coalesce(jsonb_agg(
           jsonb_build_object(
             'visitor_id', m.visitor_id,
             'name', v.display_name,
             'track_id', m.track_id,
             'joined_at', m.joined_at
           )
           -- Owner first, then arrival order — the same order the roster is
           -- sorted into on the client, so the payload is already displayable.
           order by (m.visitor_id = v_room.owner_id) desc, m.joined_at
         ), '[]'::jsonb)
  into v_members
  from public.room_members m
  join public.visitors v on v.id = m.visitor_id
  where m.room_id = v_room.id;

  return jsonb_build_object(
    'id', v_room.id,
    'name', v_room.name,
    'join_code', v_room.join_code,
    'owner_id', v_room.owner_id,
    'created_at', v_room.created_at,
    'members', v_members
  );
end;
$$;

create or replace function public.create_room(
  p_visitor_id uuid,
  p_name text,
  p_track_id public.track_id
)
returns public.rooms
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_room public.rooms;
  v_name text := left(btrim(coalesce(p_name, '')), 24);
  v_code text;
  v_attempt integer := 0;
begin
  if p_visitor_id is null then
    raise exception 'unknown_visitor' using errcode = 'P0001';
  end if;

  if char_length(v_name) = 0 then
    raise exception 'invalid_name' using errcode = 'P0001';
  end if;

  -- Naming the visitor is what creates them, so there is no ordering to
  -- enforce between "tell me your name" and "make me a room".
  perform public.claim_visitor(p_visitor_id, p_name);

  loop
    v_code := public.generate_join_code();
    exit when not exists (select 1 from public.rooms where join_code = v_code);
    v_attempt := v_attempt + 1;
    if v_attempt > 5 then
      raise exception 'code_collision' using errcode = 'P0001';
    end if;
  end loop;

  insert into public.rooms (name, join_code, owner_id)
  values (v_name, v_code, p_visitor_id)
  returning * into v_room;

  -- The owner occupies a seat like anyone else.
  insert into public.room_members (room_id, visitor_id, track_id)
  values (v_room.id, p_visitor_id, p_track_id);

  update public.visitors set track_id = p_track_id where id = p_visitor_id;

  return v_room;
end;
$$;

create or replace function public.join_room(
  p_visitor_id uuid,
  p_code text,
  p_track_id public.track_id
)
returns public.rooms
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_room public.rooms;
  v_code text := upper(btrim(coalesce(p_code, '')));
begin
  if p_visitor_id is null then
    raise exception 'unknown_visitor' using errcode = 'P0001';
  end if;

  -- Unlike create_room, joining does not name the visitor: the room screen
  -- asks for a name first. Requiring one here would let a caller invent a
  -- second identity simply by trying the wrong door.
  if not exists (select 1 from public.visitors where id = p_visitor_id) then
    raise exception 'unknown_visitor' using errcode = 'P0001';
  end if;

  -- Mirrors `normalizeJoinCode` in the app. Checking the shape here rather than
  -- only the emptiness gives a mistyped code the precise "that is not a code"
  -- answer instead of the "no such room" it would otherwise get — which reads
  -- as the room not existing rather than as the visitor having typed it wrong.
  if v_code !~ '^[0-9A-F]{6}$' then
    raise exception 'invalid_code' using errcode = 'P0001';
  end if;

  select * into v_room from public.rooms where join_code = v_code;

  if not found then
    raise exception 'room_not_found' using errcode = 'P0001';
  end if;

  if exists (
    select 1 from public.room_members
    where room_id = v_room.id and visitor_id = p_visitor_id
  ) then
    raise exception 'already_joined' using errcode = 'P0001';
  end if;

  if (select count(*) from public.room_members where room_id = v_room.id) >= 4 then
    raise exception 'room_full' using errcode = 'P0001';
  end if;

  -- A duplicate (room_id, track_id) raises 23505, which the app maps to
  -- "that track is already taken in this room".
  insert into public.room_members (room_id, visitor_id, track_id)
  values (v_room.id, p_visitor_id, p_track_id);

  update public.visitors set track_id = p_track_id where id = p_visitor_id;

  return v_room;
end;
$$;

create or replace function public.rename_room(
  p_visitor_id uuid,
  p_room_id uuid,
  p_name text
)
returns public.rooms
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_room public.rooms;
  v_name text := left(btrim(coalesce(p_name, '')), 24);
begin
  if p_visitor_id is null then
    raise exception 'unknown_visitor' using errcode = 'P0001';
  end if;

  if char_length(v_name) = 0 then
    raise exception 'invalid_name' using errcode = 'P0001';
  end if;

  if not exists (
    select 1 from public.rooms
    where id = p_room_id and owner_id = p_visitor_id
  ) then
    raise exception 'not_room_owner' using errcode = '42501';
  end if;

  update public.rooms set name = v_name where id = p_room_id returning * into v_room;
  return v_room;
end;
$$;

create or replace function public.leave_room(p_visitor_id uuid, p_room_id uuid)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
begin
  if p_visitor_id is null then
    raise exception 'unknown_visitor' using errcode = 'P0001';
  end if;

  delete from public.room_members
  where room_id = p_room_id and visitor_id = p_visitor_id;

  return found;
end;
$$;

-- ------------------------------------------------------------------ --
-- Grants
--
-- `anon` gets no table privileges whatsoever — only EXECUTE on the functions
-- above. That is the access model, and it is what lets the rules live in the
-- database rather than in the UI.
--
-- `PUBLIC` is spelled in caps and quoted on purpose: unquoted lowercase
-- `public` is the *schema*, so `revoke … from public` silently revokes from
-- nothing and every caller keeps EXECUTE.
-- ------------------------------------------------------------------ --

revoke all on table public.visitors from PUBLIC, anon, authenticated;
revoke all on table public.rooms from PUBLIC, anon, authenticated;
revoke all on table public.room_members from PUBLIC, anon, authenticated;

revoke execute on function public.claim_visitor(uuid, text) from PUBLIC;
revoke execute on function public.get_room(text) from PUBLIC;
revoke execute on function public.create_room(uuid, text, public.track_id) from PUBLIC;
revoke execute on function public.join_room(uuid, text, public.track_id) from PUBLIC;
revoke execute on function public.rename_room(uuid, uuid, text) from PUBLIC;
revoke execute on function public.leave_room(uuid, uuid) from PUBLIC;

-- These three are internals. `revoke … from PUBLIC` is not enough on its own:
-- the `alter default privileges` below already granted `anon` a direct
-- privilege when these were created, and a direct grant survives a revoke from
-- PUBLIC. Trigger functions cannot be called as RPCs, but `generate_join_code`
-- returns text and would be a publicly callable function for no benefit.
revoke execute on function public.enforce_room_cap_four() from PUBLIC, anon, authenticated;
revoke execute on function public.touch_updated_at() from PUBLIC, anon, authenticated;
revoke execute on function public.generate_join_code() from PUBLIC, anon, authenticated;

grant execute on function public.claim_visitor(uuid, text) to anon, authenticated;
grant execute on function public.get_room(text) to anon, authenticated;
grant execute on function public.create_room(uuid, text, public.track_id) to anon, authenticated;
grant execute on function public.join_room(uuid, text, public.track_id) to anon, authenticated;
grant execute on function public.rename_room(uuid, uuid, text) to anon, authenticated;
grant execute on function public.leave_room(uuid, uuid) to anon, authenticated;

-- Close the door for the next function too, not just the ones above.
alter default privileges in schema public revoke execute on functions from PUBLIC;
alter default privileges in schema public
  grant execute on functions to anon, authenticated, service_role;

-- ------------------------------------------------------------------ --
-- RLS
--
-- No policies, because there are no grants to gate. Left on for all three
-- tables anyway: `public` is an exposed schema, and enabling RLS means a
-- future GRANT that forgets to think about access fails closed rather than
-- shipping every visitor's name and room to anyone who guesses the table name.
-- ------------------------------------------------------------------ --

alter table public.visitors enable row level security;
alter table public.rooms enable row level security;
alter table public.room_members enable row level security;