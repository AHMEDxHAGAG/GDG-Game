/*
 * A visitor is a name and nothing else.
 *
 * `id` is generated by the browser and kept in localStorage, so a returning
 * visitor keeps the same identity — and the same rooms — without ever signing
 * in. It is not a credential and is never treated as one: it identifies, it
 * does not authenticate.
 */
create table if not exists public.visitors (
  id uuid primary key,
  display_name text not null check (char_length(display_name) between 1 and 24),
  -- What the quiz told us, kept so a room can be re-joined without re-picking.
  track_id public.track_id,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on table public.visitors is
  'One row per device. No login: id is a client-generated uuid held in localStorage.';

create table if not exists public.rooms (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(name) between 1 and 24),
  join_code text not null unique,
  owner_id uuid not null references public.visitors (id) on delete cascade,
  created_at timestamptz not null default now()
);

comment on table public.rooms is
  'A room. Joined by join_code; renamed only by owner_id. Seats four.';

create table if not exists public.room_members (
  room_id uuid not null references public.rooms (id) on delete cascade,
  visitor_id uuid not null references public.visitors (id) on delete cascade,
  track_id public.track_id not null,
  joined_at timestamptz not null default now(),
  primary key (room_id, visitor_id)
);

-- The core rule, unchanged in shape: one track per room. Four members means
-- four of the five tracks, so a room can never hold two Software Engineers.
create unique index if not exists room_members_one_track_per_room
  on public.room_members (room_id, track_id);

create index if not exists room_members_by_visitor on public.room_members (visitor_id);

