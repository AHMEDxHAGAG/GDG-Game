-- GDGoC Pirate Identity Expedition — visitor identity, and rooms of four.
--
-- Supersedes 20261012000000, which coupled everything to `auth.users`. This
-- migration removes that coupling entirely: there is no login, no account and
-- no OAuth provider. A visitor is a name plus a client-generated id, and the
-- room rules are enforced against that.
--
-- What changes, and why:
--
--   profiles     -> visitors   No `auth.users` foreign key. `id` is supplied by
--                              the client (a random uuid kept in localStorage),
--                              so the row is created by the visitor themselves.
--   teams        -> rooms      Renamed to match the Arabic UI copy, which calls
--                              them روم ("room").
--   team_members -> room_members
--   cap 5        -> cap 4      The owner is a member, so four people per room.
--
-- Everything is reached through SECURITY DEFINER functions, and `anon` is
-- granted *no table privileges at all*. That is the whole access model: there
-- is no identity to authorize against, so pushing the rules into the database
-- is what stops a mistyped join code from putting five people in a room.
--
-- What that costs, stated plainly: `p_visitor_id` is a bearer value. Anyone
-- who learns another visitor's uuid can act as them — rename their room, leave
-- it, claim it as their own. That is the same trust level as a session token
-- in localStorage, and it is the honest ceiling for a kiosk app with no login.
-- It is *not* suitable for anything where an attacker would gain something.

-- ------------------------------------------------------------------ --
-- Teardown
--
-- Order matters three times over, and every step is guarded or cascading so a
-- re-run against an already-migrated database is a no-op:
--
--   1. functions whose *signature* names a table have to go first, because
--      `returns public.rooms` is a dependency that blocks `DROP TABLE`;
--   2. then the tables, CASCADE, which takes their policies and triggers;
--   3. then the trigger functions, which those triggers were holding alive.
--
-- A `drop policy if exists … on public.profiles` would not survive a re-run
-- either: `IF EXISTS` covers the policy and not the relation.
-- ------------------------------------------------------------------ --

-- The trigger on auth.users has to go before the function it calls.
do $$
begin
  if exists (select 1 from pg_trigger where tgname = 'on_auth_user_created') then
    execute 'drop trigger if exists on_auth_user_created on auth.users';
  end if;
end;
$$;

-- 1. Everything that mentions a table by name in its signature.
drop function if exists public.create_room(uuid, text, public.track_id);
drop function if exists public.join_room(uuid, text, public.track_id);
drop function if exists public.rename_room(uuid, uuid, text);
drop function if exists public.claim_visitor(uuid, text);
drop function if exists public.get_room(text);
drop function if exists public.leave_room(uuid, uuid);
drop function if exists public.create_team(text, public.track_id);
drop function if exists public.join_team(text, public.track_id);
drop function if exists public.rename_team(uuid, text);
drop function if exists public.handle_new_user();

-- 2. The tables. CASCADE takes the policies, the cap trigger, and the foreign
--    keys with them.
drop table if exists public.room_members;
drop table if exists public.rooms;
drop table if exists public.visitors;
drop table if exists public.team_members;
drop table if exists public.teams;
drop table if exists public.profiles;

-- 3. The trigger functions, now unreferenced.
drop function if exists public.enforce_room_cap_four();
drop function if exists public.enforce_team_cap_five();
drop function if exists public.touch_updated_at();
drop function if exists public.generate_join_code();

drop schema if exists private cascade;

-- Nothing subscribes to postgres_changes any more — the room screen polls
-- instead, so that `anon` never needs SELECT on a memberships table it could
-- then enumerate. Guarded for the same re-run reason as the trigger above.
do $$
begin
  if exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'team_members'
  ) then
    execute 'alter publication supabase_realtime drop table public.team_members';
  end if;
end;
$$;

